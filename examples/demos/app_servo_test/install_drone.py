def unlock_drone(cf):
    """
    Start outer-loop flight state.
    This matches your original first-drone script.
    """
    cf.param.set_value("app.stateOuterLoop", "1")


def stop_drone(cf):
    """
    Stop / land / switch outer-loop stop state.
    This matches your original first-drone script.
    """
    cf.param.set_value("app.stateOuterLoop", "2")


def apply_mlp(cf):
    cf.param.set_value("app.statemlp", "1")


def apply_kf(cf):
    cf.param.set_value("app.statekf", "1")


def exploration_mode(cf):
    cf.param.set_value("app.stateexp", "1")


def set_initial_params(
    cf,
    MIN_THRESHOLD1=40.0,
    MAX_THRESHOLD1=90.0,
    MIN_THRESHOLD2=40.0,
    MAX_THRESHOLD2=90.0,
    maxSpeed=0.15,
    maxTurnRate=25.0,
    EI=3e-5,
    mu_f=0.4,
):
    """
    Same style as your first-drone script.
    maxSpeed and maxTurnRate are important for trajectory following speed.
    """
    cf.param.set_value("app.MIN_THRESHOLD1", str(MIN_THRESHOLD1))
    cf.param.set_value("app.MAX_THRESHOLD1", str(MAX_THRESHOLD1))
    cf.param.set_value("app.MIN_THRESHOLD2", str(MIN_THRESHOLD2))
    cf.param.set_value("app.MAX_THRESHOLD2", str(MAX_THRESHOLD2))

    cf.param.set_value("app.maxSpeed", str(maxSpeed))
    cf.param.set_value("app.maxTurnRate", str(maxTurnRate))

    cf.param.set_value("kalman.MU_FRICTION", str(mu_f))
    cf.param.set_value("kalman.EI_CONST", str(EI))


def set_servo_params(
    cf,
    target_distance=60.0,
    kp_d=3.0,
    ki_d=2.0,
    kd_d=0.05,
    kp_o=3.0,
    ki_o=1.0,
    kd_o=0.05,
):
    """
    Keep same servo params as your original script, in case firmware needs them.
    """
    cf.param.set_value("app.tgtDist", str(target_distance))
    cf.param.set_value("app.kp_d", str(kp_d))
    cf.param.set_value("app.ki_d", str(ki_d))
    cf.param.set_value("app.kd_d", str(kd_d))
    cf.param.set_value("app.kp_o", str(kp_o))
    cf.param.set_value("app.ki_o", str(ki_o))
    cf.param.set_value("app.kd_o", str(kd_o))


